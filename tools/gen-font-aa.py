#!/usr/bin/env python3
"""Generate 8x12 grayscale alpha atlas from installed mono fonts.
Only generated pixel coverage values are shipped; font binaries are not included.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
root = Path(__file__).resolve().parent.parent
names = [
    'DejaVuSansMono-Bold.ttf', 'DejaVuSansMono.ttf',
    'Cousine-Regular.ttf', 'Cousine-Bold.ttf',
]
folders = [Path('/usr/share/fonts/truetype/dejavu'), Path('/usr/share/fonts/truetype/croscore')]
faces = []
for name in names:
    path = next((p/name for p in folders if (p/name).exists()), None)
    if path is None:
        raise SystemExit(f'Font not installed for regeneration: {name}')
    font = ImageFont.truetype(str(path), 11)
    face = []
    for code in range(32,127):
        im = Image.new('L',(8,12),0)
        draw = ImageDraw.Draw(im)
        draw.text((0,9),chr(code),font=font,fill=255,anchor='ls')
        if code == 95:
            draw.line((0,10,6,10),fill=255)
        face.append(list(im.get_flattened_data()))
    faces.append(face)
path = root/'include/font8x12_aa.h'
with path.open('w') as f:
    f.write('/* Pre-rasterized alpha coverage, 8x12 monospace glyphs, ASCII 32..126.\n'
            ' * DejaVu Mono (Vera license), Cousine (SIL OFL); no TTF files included.\n'
            ' * Generated by tools/gen-font-aa.py. */\n'
            '#ifndef XSSH_FONT8X12_AA_H\n#define XSSH_FONT8X12_AA_H\n'
            '#include <stdint.h>\n'
            'static const uint8_t xssh_fonts_aa[4][95][12][8] = {\n')
    for i, face in enumerate(faces):
        f.write(' { /* '+names[i]+' */\n')
        for glyph in face:
            f.write('  {\n')
            for y in range(12):
                f.write('   {'+','.join(str(n) for n in glyph[y*8:(y+1)*8])+'},\n')
            f.write('  },\n')
        f.write(' },\n')
    f.write('};\n#endif\n')
print('Wrote',path)
